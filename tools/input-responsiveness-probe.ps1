;;; transport-fixture.el --- Source transport fixture -*- lexical-binding: t; -*-
(require 'cl-lib)
(defmacro seq (&rest forms) `(progn ,@forms))
(defmacro data-addr (symbol) `(sxhash ',symbol))
(defmacro addr-of (symbol) `',symbol)
(defmacro extern-call (symbol &rest args) `(fixture-extern ',symbol ,@args))
(defvar heap) (defvar output) (defvar now) (defvar fail-open)
(defvar response-lines) (defvar sources) (defvar source-id) (defvar refresh-count)
(defvar fail-write) (defvar fail-close)
(defun ptr-read-u64 (base offset) (gethash (cons base offset) heap 0))
(defun ptr-write-u64 (base offset value) (puthash (cons base offset) value heap))
(defun fixture-extern (name &rest args)
  (pcase name
    ('strncmp (if (and (stringp (car args)) (string-prefix-p "mode:" (car args))) 0 1))
    ('strcmp 1)
    ('strdup (copy-sequence (car args)))
    ('fopen (if (and fail-open (= (car args) (data-addr requests))) 0 1))
    ('fputs (setq output (append output (list (car args)))) 1)
    ('ferror (if fail-write 1 0))
    ('fclose (if fail-close -1 0)) ('free 0)
    ('g_get_monotonic_time now)
    ('g_source_remove (setq sources (assq-delete-all (car args) sources)) 1)
    ('g_timeout_add (push (cons (cl-incf source-id) (car args)) sources) source-id)
    ('fgets (if response-lines (progn (ptr-write-u64 (car args) 0 (pop response-lines)) 1) 0))
    ('strtol (string-to-number (ptr-read-u64 (car args) 0)))
    ('strcpy (ptr-write-u64 (car args) 0 (ptr-read-u64 (cadr args) 0)))
    (_ (error "Unexpected foreign call: %S" name))))
(defun cancel_graph_gestures (&rest _) 0)
(defun trim_line (&rest _) 0)
(defun refresh_session (&rest _) (cl-incf refresh-count))
(defun flush_graph_scroll (&rest _) 0)
(defun redraw_if_changed (&rest _) 0)
;; Entry echo has a separate native GTK fixture. Keep this transport fixture
;; focused on its twelve original queue/ack/timer/failure assertions.
(defun entry_echo (&rest _) 0)
(defun theme_evidence (&rest _) 0)
(defun fixture-reset ()
  (setq heap (make-hash-table :test 'equal) output nil now 1000000 fail-open nil
        sources nil source-id 0 refresh-count 0 response-lines nil fail-write nil fail-close nil)
  (dolist (pair '((160 . 90000) (3480 . 1) (64 . 91000) (72 . 92000) (80 . 93000)
                  (16 . 94000) (88 . 95000)))
    (ptr-write-u64 1 (car pair) (cdr pair))))
(defun fixture-assert (condition name) (unless condition (error "FAIL: %s" name)))
(with-temp-buffer
  (insert-file-contents (getenv "CALC_TRANSPORT_SOURCE")) (check-parens) (goto-char (point-min))
  (let* ((forms (cdr (read (current-buffer))))
         (names '(send_command flush_batch flush_command update_wait_timer timer_boundary_check poll_response)))
    (dolist (form forms)
      (when (and (eq (car-safe form) 'defun) (memq (cadr form) names)) (eval form t)))))
(fixture-reset)
(send_command 1 "1\n")
(fixture-assert (and (= (length output) 1) (= (ptr-read-u64 1 40) 1)) 'immediate-idle-submit)
(princ "INPUT-CASE-PASS immediate-idle-submit\n")
