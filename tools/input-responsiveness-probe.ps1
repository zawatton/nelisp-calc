(fixture-assert (and (= (ptr-read-u64 1 32) 100) (= (ptr-read-u64 1 40) 1)
                     (= (length output) 2)) 'external-ack-jump-no-underflow)
(princ "INPUT-CASE-PASS external-ack-jump\n")
