                       (= (cdar sources) 100)) 'fail-stop-no-replay-or-stale-accept)
  (princ (format "INPUT-CASE-PASS %s-failure-fail-stop\n" failure)))
(fixture-reset) (send_command 1 "1\n") (send_command 1 "2\n")
