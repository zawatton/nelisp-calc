(fixture-assert (= (length output) 1) 'no-submit-before-ack)
(ptr-write-u64 1 32 1) (ptr-write-u64 1 40 0) (flush_command 1)
(fixture-assert (and (= (length output) 17) (= (ptr-read-u64 1 40) 16)
                     (equal (cdr output) (cl-loop for i below 16 collect (format "%d\n" i)))) 'bounded-ordered-batch)
(princ "INPUT-CASE-PASS bounded-ordered-batch\n")
(setq response-lines '("partial" "old" "8")) (poll_response 1)
(fixture-assert (and (= (ptr-read-u64 1 32) 8) (= (ptr-read-u64 1 40) 9)
                     (= refresh-count 1) (= (length output) 17)) 'partial-ack-not-final)
;; An older publication must neither replace the partial result nor release tail.
(setq response-lines '("stale" "old" "7")) (poll_response 1)
(fixture-assert (and (= (ptr-read-u64 1 32) 8) (= (ptr-read-u64 1 40) 9)
                     (= refresh-count 1) (= (length output) 17)) 'stale-partial-rejected)
(princ "INPUT-CASE-PASS partial-ack-not-final\n")
(setq response-lines '("final" "ready" "17")) (poll_response 1)
(fixture-assert (and (= (ptr-read-u64 1 32) 17) (= (ptr-read-u64 1 40) 4)
                     (= refresh-count 2) (= (length output) 21)) 'final-ack-drains-tail)
(princ "INPUT-CASE-PASS final-ack-drains-tail\n")
(fixture-reset) (ptr-write-u64 1 40 1)
(dotimes (i 65) (send_command 1 "9\n"))
(fixture-assert (and (= (ptr-read-u64 1 152) 64) (= (ptr-read-u64 1 136) 1)) 'overflow-preserves-ring)
(princ "INPUT-CASE-PASS overflow-preserves-ring\n")
(fixture-reset) (setq fail-open t) (send_command 1 "7\n")
(fixture-assert (and (= (ptr-read-u64 1 144) 0) (= (ptr-read-u64 1 40) 0)
                     (= (ptr-read-u64 1 168) (+ now 90000000))) 'open-failure-retains-token)
(setq now (+ now 90000001)) (flush_command 1)
(fixture-assert (= (ptr-read-u64 1 24) (data-addr unavailable)) 'open-failure-real-deadline)
(setq fail-open nil) (flush_command 1)
(fixture-assert (equal output '("7\n")) 'open-recovery-no-duplicate)
(princ "INPUT-CASE-PASS open-failure-recovery\n")
(fixture-reset) (fixture-assert (= (timer_boundary_check 1) 0) 'real-wait-deadline)
(princ "INPUT-CASE-PASS real-wait-deadline\n")
(fixture-reset) (ptr-write-u64 1 8752 100)
(ptr-write-u64 1 8744 (fixture-extern 'g_timeout_add 100 'poll_response 1))
(send_command 1 "1\n") (send_command 1 "2\n")
(fixture-assert (and (= (length sources) 1) (= source-id 2) (= (cdar sources) 10)) 'single-woken-source)
;; The firing source has already been removed by GLib before its callback.
(setq sources nil) (setq response-lines '("done" "ready" "1")) (poll_response 1)
(fixture-assert (and (= (length sources) 1) (= (cdar sources) 10)) 'single-active-source)
(setq sources nil response-lines '("done" "ready" "2")) (poll_response 1)
(fixture-assert (and (= (length sources) 1) (= (cdar sources) 100)) 'idle-cadence-restored)
(princ "INPUT-CASE-PASS single-adaptive-source\n")
