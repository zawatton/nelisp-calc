(setq response-lines '("initial" "ready" "0")) (poll_response 1)
(fixture-assert (and (= (ptr-read-u64 1 3480) 1) (= (ptr-read-u64 1 32) 0)
                     (equal (ptr-read-u64 94000 0) "initial")) 'initial-ready-zero)
(setq sources nil response-lines '("feedback" "changed" "0")) (poll_response 1)
(fixture-assert (and (= refresh-count 0) (= (ptr-read-u64 1 40) 0)
                     (equal (ptr-read-u64 94000 0) "feedback")
                     (equal (ptr-read-u64 95000 0) "changed")) 'idle-same-count-feedback)
(princ "INPUT-CASE-PASS initial-and-idle-same-count\nINPUT-RESPONSIVENESS-PASS cases=12\n")
